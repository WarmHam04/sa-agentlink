CREATE TABLE agentlink_workflow (
    context_id       VARCHAR(128) PRIMARY KEY,
    goal             TEXT NOT NULL,
    definition_hash  VARCHAR(64) NOT NULL,
    snapshot_json    TEXT NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE agentlink_task_event (
    event_offset  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    context_id    VARCHAR(128) NOT NULL,
    task_id       VARCHAR(128) NOT NULL,
    node_id       VARCHAR(128) NOT NULL,
    state         VARCHAR(32) NOT NULL,
    message       TEXT,
    artifact_id   VARCHAR(128),
    event_time    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_agentlink_event_context_offset
    ON agentlink_task_event (context_id, event_offset);

CREATE TABLE agentlink_outbox (
    outbox_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_type VARCHAR(64) NOT NULL,
    aggregate_id   VARCHAR(128) NOT NULL,
    event_type     VARCHAR(128) NOT NULL,
    payload_json   TEXT NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at   TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_agentlink_outbox_unpublished
    ON agentlink_outbox (published_at, outbox_id);
